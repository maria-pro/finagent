"""Guardrails for a finance assistant.

Input rail: refuse requests to manipulate markets or misuse inside information,
and mark requests for personal advice so the answer is framed as general
information. On the NVIDIA API catalog the request also goes through the
NemoGuard topic-control NIM; on CPU the deterministic rules run alone.

Output rail: mark promissory language inline in the note (and list it in the run
summary), and always attach a disclaimer. The model's words are flagged, not
rewritten, so a reader can see exactly what was said.
"""

from __future__ import annotations

import re

from openai import OpenAI

from ..config import Settings

_PROHIBITED = [
    (r"\bpump\b.{0,40}\bdump\b|\bpump(ing)? (up )?the (price|stock)", "market manipulation"),
    (r"\bmanipulat\w*\b.{0,30}\b(price|stock|market|share)", "market manipulation"),
    (r"\b(spoof\w*|wash[- ]trad\w*|front[- ]?run\w*|layering)\b", "abusive trading practice"),
    (r"\binsider (info\w*|tip\w*|knowledge)\b|\bnon[- ]public (info\w*|results)\b|\bbefore (it'?s|they are) (announced|public)\b", "trading on inside information"),
    (r"\blaunder\w*\b|\bevade (tax\w*|sanction\w*)\b|\bhide (money|assets) from\b", "financial crime"),
]
_PERSONAL_ADVICE = re.compile(
    r"\bshould i (buy|sell|invest|hold|short)\b|\bmy (savings|retirement|pension|portfolio|super)\b|\ball[- ]in\b|\bput (all|everything)\b",
    re.I,
)
_PROMISSORY = re.compile(
    r"\b(guaranteed?|risk[- ]free (return|profit)|can(no|')t lose|sure thing|will definitely|certain to (rise|double|go up))\b",
    re.I,
)

DISCLAIMER = (
    "This note was generated by AI agents for educational purposes. It is general information, "
    "not personal financial advice or a recommendation to buy or sell any security. Figures come from "
    "public data (SEC EDGAR, US Treasury, Yahoo Finance) and may contain errors; verify before relying on them."
)

TOPIC_POLICY = """You are a topic-control rail for an equity research assistant.
Allowed: questions about public companies, stocks, ETFs, financial statements, valuation, market performance, investment risk and economics, asked for research or education.
Not allowed: requests to manipulate markets, trade on inside or non-public information, evade laws, or anything unrelated to finance and investing.
If any of the above conditions are violated, please respond with "off-topic". Otherwise, respond with "on-topic". You must respond with "on-topic" or "off-topic"."""


def check_input(settings: Settings, question: str) -> dict:
    for pattern, reason in _PROHIBITED:
        if re.search(pattern, question, re.I):
            return {"allowed": False, "reason": reason, "rail": "rules"}

    decision = {"allowed": True, "personal_advice": bool(_PERSONAL_ADVICE.search(question)), "rail": "rules"}
    if settings.guard_model:
        try:
            client = OpenAI(base_url=settings.base_url, api_key=settings.api_key or "not-needed", timeout=30)
            verdict = client.chat.completions.create(
                model=settings.guard_model,
                messages=[{"role": "system", "content": TOPIC_POLICY}, {"role": "user", "content": question}],
                max_tokens=8,
                temperature=0,
            ).choices[0].message.content or ""
            decision["rail"] = f"rules + {settings.guard_model}"
            if "off-topic" in verdict.lower():
                return {"allowed": False, "reason": "outside the assistant's research scope", "rail": decision["rail"]}
        except Exception as err:
            decision["rail"] = f"rules (topic rail unavailable: {type(err).__name__})"
    return decision


def refusal_message(reason: str) -> str:
    return (
        f"I can't help with that request ({reason}). FinAgent produces educational research on public "
        "companies from public data. Try asking about a company's performance, fundamentals, valuation or risks."
    )


def check_output(text: str) -> list[str]:
    """Phrases that over-promise; listed in the run summary."""
    return sorted({m.group(0) for m in _PROMISSORY.finditer(text)})


def flag_promissory(text: str, marker: str = " ⚠promissory") -> str:
    """Mark each over-promising phrase where it occurs in the note."""
    return _PROMISSORY.sub(lambda m: m.group(0) + marker, text)
